/**
 * Pre-computes the land dots for the homepage hero globe, so the `dotted-map`
 * package and its world geometry never reach the browser — the same approach as
 * scripts/generate-world-map.mjs. Run after changing density:
 *
 *   node scripts/generate-globe-points.mjs
 *
 * Output: src/components/home/globePoints.generated.ts — a flat
 * [lat, lng, lat, lng, …] list, only ever imported by the lazily loaded globe.
 *
 * An equirectangular grid crowds dots together toward the poles once wrapped
 * onto a sphere, so points are thinned in proportion to cos(latitude) with a
 * fixed pseudo-random sequence (the output is stable between runs).
 */
import { writeFileSync } from 'node:fs'
import DottedMap from 'dotted-map'

const OUT = 'src/components/home/globePoints.generated.ts'
const HEIGHT = 80
const REGION = { lat: { min: -58, max: 78 }, lng: { min: -180, max: 180 } }

const map = new DottedMap({ height: HEIGHT, grid: 'diagonal', projection: { name: 'equirectangular' }, region: REGION })
const { width, height } = map.image

// Deterministic 0..1 sequence.
let seed = 42
const random = () => {
  seed = (seed * 1664525 + 1013904223) % 4294967296
  return seed / 4294967296
}

const coords = []
for (const { x, y } of map.getPoints()) {
  const lng = (x / width) * (REGION.lng.max - REGION.lng.min) + REGION.lng.min
  const lat = REGION.lat.max - (y / height) * (REGION.lat.max - REGION.lat.min)
  if (random() > Math.cos((lat * Math.PI) / 180)) continue
  coords.push(Math.round(lat * 10) / 10, Math.round(lng * 10) / 10)
}

writeFileSync(
  OUT,
  `// Generated by scripts/generate-globe-points.mjs — do not edit by hand.\n` +
    `// ${coords.length / 2} land points as [lat, lng, lat, lng, …].\n` +
    `export const globePoints = new Float32Array([${coords.join(',')}])\n`
)
console.log(`generated ${OUT} (${coords.length / 2} points)`)
